//! Aliases for standard Rust types to be used by the models in this crate.

/// The identifier of a network.
pub type NetworkId = i16;

/// Identifier of a machine.
pub type MachineId = i32;

/// Identifier of a drive.
pub type DriveId = String;

/// The address of a remote-hands service.
pub type RemoteAddress = String;
